def run():
    print("=" * 75)
    print("🏢 启动全库 109 个待汉化厂牌精准命名与深度档案入库程序")
    print("=" * 75)

    conn = sqlite3.connect(GPDB_PATH)
    cur = conn.cursor()

    trans_conn = sqlite3.connect(TRANS_PATH)
    trans_cur = trans_conn.cursor()

    updated_count = 0
    for sid, data in STUDIO_DATA.items():
        name_zh = data["name_zh"].strip()
        desc_zh = data["desc"].strip()

        # 1. 查询英文原名
        cur.execute("SELECT name FROM studios WHERE id = ?", (sid,))
        row = cur.fetchone()
        if not row:
            continue
        original_name = row[0]

        # 2. 更新 GPDb.db 中的 studios 表
        cur.execute("""
            UPDATE studios
            SET name_zh = ?,
                description_zh = ?,
                updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
        """, (name_zh, desc_zh, sid))

        # 3. 双写入 translations.db
        # 3.1 厂牌中文名
        trans_cur.execute("""
            INSERT INTO translations (entity_type, entity_id, field, source_lang, target_lang, src_text, trans_text, updated_at)
            VALUES ('studio', ?, 'name', 'en', 'zh-CN', ?, ?, CURRENT_TIMESTAMP)
            ON CONFLICT(entity_type, entity_id, field, target_lang)
            DO UPDATE SET trans_text = excluded.trans_text, updated_at = CURRENT_TIMESTAMP
        """, (sid, original_name, name_zh))

        # 3.2 厂牌介绍
        trans_cur.execute("""
            INSERT INTO translations (entity_type, entity_id, field, source_lang, target_lang, src_text, trans_text, updated_at)
            VALUES ('studio', ?, 'description', 'en', 'zh-CN', ?, ?, CURRENT_TIMESTAMP)
            ON CONFLICT(entity_type, entity_id, field, target_lang)
            DO UPDATE SET trans_text = excluded.trans_text, updated_at = CURRENT_TIMESTAMP
        """, (sid, original_name, desc_zh))

        updated_count += 1
        print(f"[{updated_count}/109] 厂牌 ID {sid:>3}: {original_name:<30} -> 【{name_zh}】(已入库，档案字数: {len(desc_zh)})")

    conn.commit()
    conn.close()

    trans_conn.commit()
    trans_conn.close()

    print("\n" + "=" * 75)
    print(f"🎉 全部 109 个厂牌中文命名与深度历史档案已 100% 成功录入数据库！")
    print("=" * 75)


if __name__ == "__main__":
    run()
